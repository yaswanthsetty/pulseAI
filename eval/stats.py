"""Statistics for the eval suites: Wilson intervals and the paired bootstrap.

Plan §2.4 wants every interval visible rather than hidden; §2.1's ablation
needs to know whether a config's gap over the production default is real on
this query set. Two tools, both honest about their denominators:

* :func:`wilson_interval` — a binomial proportion's 95% interval.
* :func:`paired_bootstrap_delta` — the 95% CI of a **paired** mean difference
  over queries (the same resampled query indices drive both configs), with a
  fixed seed so the interval is reproducible in a committed results file.
"""

from __future__ import annotations

from collections.abc import Sequence
from math import sqrt
from typing import Any

Z_95 = 1.96

# Fixed so a results file can be regenerated byte-for-byte: an interval that
# moves when it is re-run is not evidence.
BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 20261013


def wilson_interval(successes: int, n: int, z: float = Z_95) -> tuple[float, float]:
    """95% Wilson score interval for a binomial proportion.

    Returns ``(low, high)``; at n=0 returns ``(0.0, 1.0)`` (fully uncertain).
    """
    if n == 0:
        return 0.0, 1.0
    p = successes / n
    denominator = 1 + z**2 / n
    centre = (p + z**2 / (2 * n)) / denominator
    margin = (z / denominator) * sqrt(p * (1 - p) / n + z**2 / (4 * n**2))
    return max(0.0, centre - margin), min(1.0, centre + margin)


def precision_recall(
    predicted_positive: list[bool], ground_truth: list[bool]
) -> dict[str, float | int | tuple[float, float] | None]:
    """Precision/recall with Wilson intervals (positive = boilerplate).

    ``precision`` is ``None`` when nothing was predicted positive: with an
    empty denominator precision is undefined, and reporting it as 0.000 would
    read as "every prediction was wrong" when in fact there were no
    predictions at all.
    """
    if len(predicted_positive) != len(ground_truth):
        raise ValueError("length mismatch")
    tp = sum(
        1 for pred, truth in zip(predicted_positive, ground_truth, strict=True) if pred and truth
    )
    fp = sum(
        1
        for pred, truth in zip(predicted_positive, ground_truth, strict=True)
        if pred and not truth
    )
    fn = sum(
        1
        for pred, truth in zip(predicted_positive, ground_truth, strict=True)
        if not pred and truth
    )
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else 0.0
    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": precision,
        "precision_ci95": wilson_interval(tp, tp + fp),
        "recall": recall,
        "recall_ci95": wilson_interval(tp, tp + fn),
    }


def percentile(sorted_values: Sequence[float], quantile: float) -> float:
    """Nearest-rank percentile of an ascending sequence (``quantile`` in [0, 1])."""
    if not sorted_values:
        raise ValueError("empty sample")
    index = min(len(sorted_values) - 1, max(0, int(round(quantile * (len(sorted_values) - 1)))))
    return float(sorted_values[index])


def paired_bootstrap_delta(
    a: Sequence[float | None],
    b: Sequence[float | None],
    *,
    resamples: int = BOOTSTRAP_RESAMPLES,
    seed: int = BOOTSTRAP_SEED,
    confidence: float = 0.95,
) -> dict[str, Any]:
    """95% CI for ``mean(a - b)`` over the queries **both** sides define.

    Paired: each resample draws one set of query indices and uses it for both
    configs, so the interval is about the difference on *this* query set. The
    point delta is the plain mean difference; a CI that excludes 0 is the only
    thing here that may be called a difference, and even then it is a
    difference on 60 queries, not a fact about retrieval in general.

    Queries where either side is ``None`` (undefined metric) are dropped and
    counted in ``dropped`` — never silently treated as 0.
    """
    if len(a) != len(b):
        raise ValueError("length mismatch")
    import numpy as np  # local: keep the module importable without the stack

    differences = np.asarray(
        [x - y for x, y in zip(a, b, strict=True) if x is not None and y is not None],
        dtype=float,
    )
    n = int(differences.size)
    delta = float(differences.mean()) if n else None
    if n == 0:
        return {
            "n": 0,
            "delta": None,
            "ci95": None,
            "excludes_zero": False,
            "dropped": len(a),
            "resamples": resamples,
            "seed": seed,
        }
    rng = np.random.default_rng(seed)
    draws = differences[rng.integers(0, n, size=(resamples, n))].mean(axis=1)
    low, high = np.percentile(draws, [100 * (1 - confidence) / 2, 100 * (1 + confidence) / 2])
    return {
        "n": n,
        "delta": delta,
        "ci95": [float(low), float(high)],
        "excludes_zero": bool(low > 0 or high < 0),
        "dropped": len(a) - n,
        "resamples": resamples,
        "seed": seed,
    }
